export const STRINGS: Record<Lang, Dict> = { en: EN, "pt-BR": PT, es: ES, fr: FR };

export type Vars = Record<string, string | number>;

/** The text for `key` in `lang`, with {name} placeholders filled in. A missing translation falls back to English. */
export function translate(lang: Lang, key: StringKey, vars?: Vars): string {
	const raw = STRINGS[lang]?.[key] || STRINGS.en[key] || key;
	if (!vars) return raw;
	return raw.replace(/\{(\w+)\}/g, (m, name: string) => (name in vars ? String(vars[name]) : m));
}

/** The {placeholders} a string uses, sorted. Tests compare these across languages. */
export function placeholders(s: string): string[] {
	return Array.from(s.matchAll(/\{(\w+)\}/g), (m) => m[1]).sort();
}
